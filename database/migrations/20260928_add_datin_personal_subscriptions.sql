CREATE TABLE datin_institutions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  name VARCHAR(255) NOT NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_datin_institution_name (name)
);

CREATE TABLE datin_institution_aliases (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  institution_id BIGINT UNSIGNED NOT NULL,
  cacti_group_name VARCHAR(255) NOT NULL,
  normalized_name VARCHAR(255) NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_datin_institution_alias (normalized_name),
  KEY idx_datin_alias_institution (institution_id),
  CONSTRAINT fk_datin_alias_institution FOREIGN KEY (institution_id) REFERENCES datin_institutions(id)
);

CREATE TABLE telegram_datin_subscriptions (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  telegram_user_id BIGINT NOT NULL,
  institution_id BIGINT UNSIGNED NOT NULL,
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_telegram_datin_institution (telegram_user_id, institution_id),
  KEY idx_telegram_datin_subscription_active (institution_id, is_active),
  CONSTRAINT fk_telegram_datin_institution FOREIGN KEY (institution_id) REFERENCES datin_institutions(id)
);

